export function createPRNG(seed: number) {
  let s = Math.abs(seed | 0) + 1;
  return function () {
    s = (s + 0x6d2b79f5) | 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function mirrorPicture(rows: string[]): string[] {
  return rows.map((row) => row.split('').reverse().join(''));
}

export function rotatePicture90(rows: string[]): string[] {
  const h = rows.length;
  const w = rows[0].length;
  const result: string[] = [];
  for (let c = 0; c < w; c++) {
    let newRow = '';
    for (let r = h - 1; r >= 0; r--) {
      newRow += rows[r][c] || '.';
    }
    result.push(newRow);
  }
  return result;
}
